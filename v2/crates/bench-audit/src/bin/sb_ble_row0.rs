// Vol-125 INVENTION — SB-BLE (Super-Block Bandwidth-Limited Enumeration)
//
// Phase 0: enumerate row-0 internally-valid super-block sequences.
// Each row-0 super-block must have:
//   - North edges = BORDER (since sr=0)
//   - East-West edges match between adjacent cells
//   - Pieces used within row are distinct (32 pieces in row 0)
//   - Corner sc=0 must have piece in TL with W=BORDER too (already enforced by alphabet)
//   - Corner sc=7 must have piece in TR with E=BORDER (already enforced)
//   - Canonical hints applied (one hint cell in row 1, but we may have hint in row 0
//     too — only positions (1,1), (1,6), (4,3), (6,1), (6,6) — none in row 0 actually).
//
// Output: count + sample sequences to /tmp/sb_ble_row0_count.txt
//
// Constants for canonical 5-hint Eternity II.

#![forbid(unsafe_code)]

use std::fs;
use std::path::PathBuf;
use std::time::Instant;

const SW: usize = 8;
const BORDER: u8 = 23; // canonical Eternity II border color is encoded as 23

#[derive(Debug, Clone, Copy)]
struct Block {
    pieces: [u16; 4],
    rots: [u8; 4],
    /// edge[N|E|S|W] = (color1, color2) of that 2-cell super-edge
    edge: [[u8; 2]; 4],
}
const N: usize = 0;
const E: usize = 1;
const S: usize = 2;
const W: usize = 3;

fn read_blocks(path: &PathBuf) -> Vec<Block> {
    let bytes = fs::read(path).expect("read alphabet file");
    assert_eq!(&bytes[..4], b"W14B");
    let n = u32::from_le_bytes(bytes[4..8].try_into().unwrap()) as usize;
    let mut blocks = Vec::with_capacity(n);
    let mut off = 8;
    for _ in 0..n {
        let mut b = Block { pieces: [0; 4], rots: [0; 4], edge: [[0; 2]; 4] };
        for j in 0..4 {
            b.pieces[j] = u16::from_le_bytes([bytes[off + 2 * j], bytes[off + 2 * j + 1]]);
        }
        off += 8;
        for j in 0..4 { b.rots[j] = bytes[off + j]; }
        off += 4;
        for s in 0..4 {
            b.edge[s].copy_from_slice(&bytes[off..off + 2]);
            off += 2;
        }
        blocks.push(b);
    }
    blocks
}

fn main() {
    let in_dir: PathBuf = "output/vol-125/w14/alphabet".into();
    eprintln!("=== SB-BLE Phase 0: enumerate row-0 internally-valid sequences ===");

    let t = Instant::now();
    let mut row0_alphabets: Vec<Vec<Block>> = Vec::with_capacity(8);
    for sc in 0..SW {
        let path = in_dir.join(format!("sc_{:02}_{:02}.bin", 0, sc));
        let blocks = read_blocks(&path);
        eprintln!("sc=(0,{}): {} blocks (north edge MUST be border)", sc, blocks.len());
        row0_alphabets.push(blocks);
    }
    eprintln!("Loaded row-0 alphabets in {:.1}s", t.elapsed().as_secs_f64());

    // Filter each cell's alphabet to ONLY blocks with N-edge = (BORDER, BORDER).
    // The alphabet was generated by w14 enum to already enforce border, but
    // let's double-check.
    let t = Instant::now();
    let mut row0_filtered: Vec<Vec<usize>> = Vec::with_capacity(8);
    for sc in 0..SW {
        let mut filtered = Vec::new();
        for (i, b) in row0_alphabets[sc].iter().enumerate() {
            if b.edge[N][0] == BORDER && b.edge[N][1] == BORDER {
                filtered.push(i);
            }
        }
        eprintln!("sc=(0,{}): {} blocks with N-border", sc, filtered.len());
        row0_filtered.push(filtered);
    }
    eprintln!("Filtered N-border in {:.1}s", t.elapsed().as_secs_f64());

    // Enumerate row-0 sequences with edge matching + intra-row piece uniqueness.
    // Use DFS with edge-pruning per-cell.
    //
    // State: (sc, partial_pieces_used_bitset[256-bit], chosen[sc])
    // Step: at sc, pick block whose W-edge matches previous E-edge, and pieces
    // disjoint from current row's pieces_used.
    //
    // We track only the COUNT, not store all (would be too many).
    let t = Instant::now();
    let mut count: u64 = 0;
    let mut samples_kept: Vec<[(usize, usize); 8]> = Vec::new(); // (sc, block_local_idx)
    let mut chosen: Vec<usize> = vec![0; SW];
    // pieces_used as Vec<bool> 256 entries
    let mut pieces_used = vec![false; 256];

    // Recursive enumerate.
    fn enumerate(
        sc: usize,
        e_constraint: Option<[u8; 2]>,
        row0_alphabets: &[Vec<Block>],
        row0_filtered: &[Vec<usize>],
        chosen: &mut [usize],
        pieces_used: &mut [bool],
        count: &mut u64,
        samples_kept: &mut Vec<[(usize, usize); 8]>,
    ) {
        if sc == SW {
            // Found a valid row.
            *count += 1;
            // Keep up to 100 sample sequences.
            if samples_kept.len() < 100 {
                let mut seq = [(0usize, 0usize); 8];
                for s in 0..SW {
                    seq[s] = (s, chosen[s]);
                }
                samples_kept.push(seq);
            }
            return;
        }
        let candidates: Vec<usize> = if sc == 0 {
            // First cell: also constrain W = BORDER.
            row0_filtered[0].iter().copied()
                .filter(|&i| {
                    let b = &row0_alphabets[0][i];
                    b.edge[W][0] == BORDER && b.edge[W][1] == BORDER
                })
                .collect()
        } else if sc == SW - 1 {
            // Last cell: also constrain E = BORDER (plus W from prev).
            row0_filtered[sc].iter().copied()
                .filter(|&i| {
                    let b = &row0_alphabets[sc][i];
                    if let Some(e_c) = e_constraint {
                        b.edge[W] == e_c && b.edge[E][0] == BORDER && b.edge[E][1] == BORDER
                    } else { false }
                })
                .collect()
        } else {
            row0_filtered[sc].iter().copied()
                .filter(|&i| {
                    let b = &row0_alphabets[sc][i];
                    if let Some(e_c) = e_constraint {
                        b.edge[W] == e_c
                    } else { true }
                })
                .collect()
        };

        for cand_idx in candidates {
            let b = &row0_alphabets[sc][cand_idx];
            // Check piece-uniqueness.
            let mut ok = true;
            for slot in 0..4 {
                let p = b.pieces[slot] as usize;
                if pieces_used[p] { ok = false; break; }
            }
            if !ok { continue; }
            // Commit.
            for slot in 0..4 {
                pieces_used[b.pieces[slot] as usize] = true;
            }
            chosen[sc] = cand_idx;
            enumerate(
                sc + 1,
                Some(b.edge[E]),
                row0_alphabets,
                row0_filtered,
                chosen,
                pieces_used,
                count,
                samples_kept,
            );
            // Uncommit.
            for slot in 0..4 {
                pieces_used[b.pieces[slot] as usize] = false;
            }
            if *count >= 100_000_000 {
                // Cap to avoid OOM.
                return;
            }
        }
    }

    enumerate(
        0,
        None,
        &row0_alphabets,
        &row0_filtered,
        &mut chosen,
        &mut pieces_used,
        &mut count,
        &mut samples_kept,
    );

    eprintln!("\nRow-0 internally-valid sequences: {}", count);
    eprintln!("Enumeration time: {:.1}s", t.elapsed().as_secs_f64());
    if !samples_kept.is_empty() {
        eprintln!("Sample sequence (sc, block_idx): {:?}", &samples_kept[0]);
    }

    // Save count for later phases.
    let out_path = "/tmp/sb_ble_row0_count.txt";
    let _ = fs::write(out_path, format!("count={}\nelapsed={:.3}s\n", count, t.elapsed().as_secs_f64()));
    eprintln!("Saved count to {}", out_path);
}
